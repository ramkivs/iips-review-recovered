/** Raised when a materialisation target would place the carrier inside a Git working tree. */
export class BrokerEvidenceOwnerCarrierLocationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'BrokerEvidenceOwnerCarrierLocationError';
  }
}

/** Walk up from `startDir` looking for a Git working tree (`.git` directory or file). */
function findRepositoryRoot(startDir: string): string | null {
  let current = path.resolve(startDir);
  for (;;) {
    if (realFs.existsSync(path.join(current, '.git'))) return current;
    const parent = path.dirname(current);
    if (parent === current) return null;
    current = parent;
  }
}

/**
 * Materialise the carrier into `targetDir` and return the written path.
 *
 * Recovery procedure (obligation O-2, act §4.3): re-materialisation from the governing PA declaration
 * is DETERMINISTIC, so the owner scope survives complete loss of the carrier file — no cloud sync, no
 * third-party transmission and no backup service is involved. It refuses a target inside a Git working
 * tree so the carrier can never be committed.
 */
export function materialiseBrokerEvidenceOwnerCarrier(
  targetDir: string,
  fs: Pick<typeof realFs, 'mkdirSync' | 'writeFileSync'> = realFs,
): string {
  const dir = path.resolve(targetDir);
  const repo = findRepositoryRoot(dir);
  if (repo !== null) {
    throw new BrokerEvidenceOwnerCarrierLocationError(
      `broker-import evidence owner carrier must live outside a Git working tree; "${dir}" is inside "${repo}"`,
    );
  }
  fs.mkdirSync(dir, { recursive: true });
  const target = path.join(dir, BROKER_EVIDENCE_OWNER_CARRIER_FILENAME);
  fs.writeFileSync(target, CANONICAL_BROKER_EVIDENCE_CARRIER_TEXT, { encoding: 'utf8' });
  return target;
}
