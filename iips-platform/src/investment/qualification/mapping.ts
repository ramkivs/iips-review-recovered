/* ----------------------------------------------------------------- helpers */

export type FieldDeclaration = {
  readonly field: string;
  readonly label: string;
  readonly type: 'number' | 'string' | 'string[]' | 'boolean';
  readonly optional: boolean;
  readonly requirement: FieldRequirement;
  readonly status: MappingStatus;
  readonly meaning: string;
  /** Unit the frozen calibration expects, e.g. `PERCENT`, `TIMES`, `INR crore`, `count`. */
  readonly engineUnit: string;
  readonly currency: string | null;
  readonly scale: string;
  readonly sourceUnit: string | null;
  readonly calibration: string;
  readonly source: FieldSource;
  readonly evidenceSource?: string;
  readonly transformation?: string;
  readonly missing?: string;
  readonly zero?: string;
  readonly invalid?: string;
  readonly confidence?: string;
  readonly period?: string;
  readonly basis?: string;
  readonly scope?: string;
  readonly freshness?: string;
  readonly dataQuality?: string;
};

const ANNUAL = 'Latest annual period (periodType=ANNUAL) at the pinned period end; no quarter, TTM or mixed-period figure is substituted';
const INSTANT = 'Balance-sheet instant at the pinned period end; the aggregate must resolve to exactly one instant (W07 one-instant rule)';
const BASIS = 'AS_FILED, or RESTATED when the dataset prefers a restatement and it is recorded; IMPUTED refused';
const SCOPE = 'CONSOLIDATED only; a standalone row or a scope substitution is refused, never silently accepted';
const FRESH_PNL = 'freshness-policy/1.0.0: P&L value no older than 200 days after period end';
const FRESH_BS = 'freshness-policy/1.0.0: balance-sheet value no older than 250 days after period end';
const QUALITY_DIRECT =
  'A canonical operating-metric record: validation=VALID, sourceClass at or above the metric’s minimum, unit equal to the canonical unit, observedAt not after the evaluation clock';
const QUALITY_DERIVED =
  'Every input is a PRESENT as-filed/restated observation in one period at one scope; any missing, nil, imputed or unavailable input blocks the derivation';

function defaultEvidenceSource(source: FieldSource, reason: string, status: MappingStatus): string {
  if (source.kind === 'OPERATING_METRIC') {
    const qualifier = status === 'CONFLICT' ? ' (calibration conflict: the canonical unit/scale/direction does not match this input)' : '';
    return `IID operating metric '${source.metricId}' in operatingMetrics.csv${qualifier}`;
  }
  if (source.kind === 'DERIVATION') return DERIVATIONS[source.derivationId].evidence;
  if (source.kind === 'ISSUER_SUBSECTOR') return 'dataset roster issuer.subSegment (governed classification field), matched against a closed vocabulary';
  return `none established — ${reason}`;
}

function defaultTransformation(source: FieldSource, status: MappingStatus, reason: string): string {
  if (status === 'CONFLICT') return 'none — no transformation makes the available source equal to this input’s calibrated meaning';
  if (status === 'UNMAPPED' || source.kind === 'NONE') return `none — no mapping authorized${reason === '' ? '' : ` (${reason})`}`;
  if (source.kind === 'OPERATING_METRIC') return 'identity — the canonical observation is passed unchanged: no scaling, currency conversion, sign change or unit reinterpretation';
  if (source.kind === 'DERIVATION') return DERIVATIONS[source.derivationId].formula;
  return 'case/separator normalisation, then exact membership of the closed vocabulary; no fuzzy or partial match';
}

function materialize(engineId: string, declaration: FieldDeclaration): FieldMapping {
  const reason = declaration.source.kind === 'NONE' ? declaration.source.reason : '';
  const balanceSheetDerivations: readonly DerivationId[] = ['GROSS_DEBT_TO_EBITDA_X', 'NET_PROFIT_TO_ASSETS_PCT', 'NET_PROFIT_TO_EQUITY_PCT'];
  const freshnessKind: 'PNL' | 'BALANCE_SHEET' =
    declaration.freshness === FRESH_BS ||
    (declaration.source.kind === 'DERIVATION' && balanceSheetDerivations.includes(declaration.source.derivationId))
      ? 'BALANCE_SHEET'
      : 'PNL';
  const units: FieldUnits = Object.freeze({
    engineUnit: declaration.engineUnit,
    currency: declaration.currency,
    scale: declaration.scale,
    sourceUnit: declaration.sourceUnit,
  });
  const status = declaration.status;
  const missing =
    declaration.missing ??
    (status === 'UNMAPPED' || status === 'CONFLICT'
      ? 'The input has no authorized source, so its absence is a structural refusal: the frozen engine would substitute a neutral default or renormalise over a partial pillar, which qualification never permits.'
      : 'An absent observation is MISSING, never zero: NIL_BY_DISCLOSURE is a positive statement and is not a value; NOT_COMPUTABLE and unavailable-source reasons are published unchanged and block the input.');
  const zero =
    declaration.zero ??
    (status === 'MAPPED'
      ? 'A reported zero is a value only when presence=PRESENT with a filing source and the canonical range admits it; NIL_BY_DISCLOSURE is not zero and never becomes one.'
      : status === 'DERIVED'
        ? 'A zero is usable only where the formula admits it; a zero denominator is refused with FIELD_ZERO_DENOMINATOR rather than divided into an infinite or silent zero result.'
        : 'Not applicable: no value can be supplied for this input, so no zero is ever fabricated.');
  const invalid =
    declaration.invalid ??
    (status === 'UNMAPPED' || status === 'CONFLICT'
      ? 'Any supplied value would be unsupported: the pairing of source and calibration is the defect, not the number.'
      : 'Non-finite values, out-of-range values, unit mismatch, unvalidated metrics, a source class below the floor, scope/period mismatch, staleness, imputation and post-dated observations are each refused with their own code.');
  const confidence =
    declaration.confidence ??
    (status === 'MAPPED'
      ? 'High: canonical, validated, filing-backed observation consumed without transformation.'
      : status === 'DERIVED'
        ? 'Reduced: derives from filings (basis=DERIVED) whose formula is declared; the engine’s bands were calibrated on as-reported metrics, and any declared deviation is surfaced on the field.'
        : status === 'CONFLICT'
          ? 'None: the calibration and the available semantics disagree, so the field must not be populated.'
          : 'None: no governed source exists for this input.');
  return Object.freeze({
    engineId,
    field: declaration.field,
    label: declaration.label,
    declaredType: declaration.type,
    optionalInInterface: declaration.optional,
    requirement: declaration.requirement,
    status,
    meaning: declaration.meaning,
    evidenceSource: declaration.evidenceSource ?? defaultEvidenceSource(declaration.source, reason, status),
    transformation: declaration.transformation ?? defaultTransformation(declaration.source, status, reason),
    period: declaration.period ?? ANNUAL,
    basis: declaration.basis ?? BASIS,
    scope: declaration.scope ?? SCOPE,
    units,
    missingSemantics: missing,
    zeroSemantics: zero,
    invalidSemantics: invalid,
    freshness: declaration.freshness ?? FRESH_PNL,
    freshnessKind,
    dataQuality: declaration.dataQuality ?? (status === 'DERIVED' ? QUALITY_DERIVED : QUALITY_DIRECT),
    confidence,
    calibrationImplication: declaration.calibration,
    source: declaration.source,
  });
}

function metric(id: MetricId): FieldSource {
  return { kind: 'OPERATING_METRIC', metricId: id };
}

function derived(id: DerivationId): FieldSource {
  return { kind: 'DERIVATION', derivationId: id };
}

function subsector(vocabulary: readonly string[]): FieldSource {
  return { kind: 'ISSUER_SUBSECTOR', vocabulary: Object.freeze([...vocabulary]) };
}

function none(reason: string): FieldSource {
  return { kind: 'NONE', reason };
}

/** Declared-but-unread input: published for audit, never a readiness obstacle. */
function unused(declaration: Omit<FieldDeclaration, 'requirement'>): FieldDeclaration {
  return { ...declaration, requirement: 'DECLARED_UNUSED' };
}

/** Decision override flag: absent means "no adverse event declared", a recorded limitation. */
function flag(field: string, label: string, engineConsumption: string, type: 'boolean' | 'string' = 'boolean'): FieldDeclaration {
  return {
    field,
    label,
    type,
    optional: true,
    requirement: 'DECISION_FLAG',
    status: 'UNMAPPED',
    meaning: `Adverse-event / governance override flag read by the frozen decision engine (${engineConsumption}).`,
    engineUnit: 'FLAG',
    currency: null,
    scale: 'boolean (or a closed literal string where the engine compares a literal)',
    sourceUnit: null,
    calibration: `Drives a decision override only. Qualification records that the dataset contract has no governed field for this declaration, so the engine will run without it; that limitation is published and never read as evidence that no adverse event occurred.`,
    source: none('the dataset contract has no adverse-event / governance declaration field'),
    freshness: 'Not applicable: a flag has no period, and its absence is not evidence.',
    dataQuality: 'No governed source; the limitation is reported rather than approximated.',
  };
}

