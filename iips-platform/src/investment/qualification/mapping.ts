/**
 * W10 — the field-level issuer-to-engine mapping registry.
 *
 * Every declared input of the 13 certified sector engines appears here exactly once, with its meaning,
 * evidence source, mapping status, transformation, period, basis, scope, units/currency/scaling,
 * missing/zero/invalid semantics, freshness, data quality, confidence and calibration implications.
 *
 * The registry is *data*, not logic. Two rules keep it honest:
 *
 *  - A field is only `MAPPED` when a canonical `MetricId` in `contracts/operatingMetrics.ts` carries the
 *    same meaning, unit and direction as the frozen calibration expects. A canonical metric that is
 *    merely similarly named, differently scaled or differently directed is `CONFLICT`, never `MAPPED`.
 *  - A field is only `DERIVED` when a closed derivation in `DERIVATIONS` computes it from canonical line
 *    items. A ratio nobody defined is `UNMAPPED`; the engine's neutral default is not a substitute.
 *
 * The frozen engine sources are never modified: the field lists are transcribed from the certified
 * `metrics/*Metrics.ts` interfaces and the consumption evidence comes from the frozen `scoring/`,
 * `decision/` and `calibration` files named in each profile.
 */
