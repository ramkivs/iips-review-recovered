/**
 * The 13 certified sector engines, in registry order. `declaredIn` names the frozen interface the field
 * list was transcribed from; the consumption evidence lives in the same engine's `scoring/`, `decision/`
 * and calibration files, which W10 reads but never modifies.
 */
function certified(engineId: string): (typeof CERTIFIED_ENGINES)[number] {
  const entry = CERTIFIED_ENGINES.find((candidate) => candidate.engineId === engineId);
  if (entry === undefined) throw new Error(`W10 mapping: ${engineId} is not in the certified engine registry`);
  return entry;
}

function profile(
  engineId: string,
  sectorFamily: EngineQualificationProfile['sectorFamily'],
  declaredIn: string,
  hasIndexSignature: boolean,
  fields: readonly FieldDeclaration[],
): EngineQualificationProfile {
  const entry = certified(engineId);
  return Object.freeze({
    engineId,
    ies: entry.ies,
    sectorFamily,
    certifiedSectorFamily: entry.sectorFamily,
    engineVersion: entry.engineVersion,
    calibrationVersion: entry.calibrationProfile,
    declaredIn,
    hasIndexSignature,
    fields: Object.freeze(fields.map((declaration) => materialize(engineId, declaration))),
  });
}

