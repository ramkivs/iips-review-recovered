#!/usr/bin/env python3
"""Assemble the single governed report from its parts and run the internal checks.

Parts (all in this directory):
  report-body.md   - title block + sections A-D (hand-authored)
  section-E-counts.md - section E (generated by sectionE.py from the matrix)
  section-FG.md    - sections F and G (hand-authored)
  section-H-matrix.md - section H (generated by build_matrix.py from matrix_data.py)

Output: docs/integration/IIPS_v3.0_CAPABILITY_MATRIX_51X17_RECONSTRUCTION_2026-10-27.md
"""
from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
TARGET = REPO / "docs" / "integration" / "IIPS_v3.0_CAPABILITY_MATRIX_51X17_RECONSTRUCTION_2026-10-27.md"
RECORD_ID = "IIPS-V3-CAPMATRIX-51X17-RECONSTRUCTION-2026-10-27-01"


def build() -> str:
    subprocess.run([sys.executable, "build_matrix.py"], cwd=HERE, check=True,
                   stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, "sectionE.py"], cwd=HERE, check=True,
                   stdout=(HERE / "section-E-counts.md").open("w"))
    parts = [
        (HERE / "report-body.md").read_text(encoding="utf-8"),
        (HERE / "section-E-counts.md").read_text(encoding="utf-8"),
        (HERE / "section-FG.md").read_text(encoding="utf-8"),
        (HERE / "section-H-matrix.md").read_text(encoding="utf-8"),
    ]
    text = "\n".join(p.rstrip("\n") + "\n" for p in parts)
    return text


def checks(text: str) -> list[tuple[str, bool, str]]:
    results = []

    def chk(name: str, ok: bool, detail: str = "") -> None:
        results.append((name, bool(ok), detail))

    chk("record id present once", text.count(RECORD_ID) == 1, str(text.count(RECORD_ID)))
    heads = re.findall(r"^## ([A-H])\. ", text, flags=re.M)
    chk("sections A-H present in order", heads == list("ABCDEFGH"), "".join(heads))
    chk("no duplicate section H", text.count("## H. The matrix") == 1)
    rows = [l for l in text.splitlines() if re.match(r"^\| \d+ \| ", l)]
    # Section B table (51) + section H table (51)
    chk("51 assessment rows + 51 matrix rows", len(rows) == 102, str(len(rows)))
    chk("no unresolved placeholder", "TODO" not in text and "TBD" not in text)
    chk("every row number appears in H", all(
        f"| {n} | " in text for n in range(1, 52)))
    chk("no claim of new authority", "no authority is created" in text.lower())
    findings = re.findall(r"^### (C-\d\d) ", text, flags=re.M)
    chk("discrepancies C-01..C-08 present",
        findings == [f"C-{i:02d}" for i in range(1, 9)], ",".join(findings))
    obs = re.findall(r"\*\*(O-\d\d)\*\*", text)
    chk("outstanding items O-01..O-10 present",
        obs == [f"O-{i:02d}" for i in range(1, 11)], ",".join(obs))
    chk("no acceptance language invented for rows 8/29/41",
        text.count("`DEFERRED`") >= 3)
    bare_na = [l for l in text.splitlines()
               if re.match(r"^\| \d+ \| ", l) and re.search(r"\|\s*NA\s*\|", l)]
    chk("no bare NA cell in any matrix/assessment row", not bare_na, str(len(bare_na)))
    chk("trailing newline", text.endswith("\n"))
    return results


def main() -> int:
    text = build()
    TARGET.write_text(text, encoding="utf-8")
    results = checks(text)
    width = max(len(n) for n, _, _ in results)
    failed = 0
    for name, ok, detail in results:
        print(f"{name:<{width}}  {'PASS' if ok else 'FAIL'}  {detail}")
        failed += 0 if ok else 1
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    print(f"\nreport bytes={len(text.encode())} sha256={digest}")
    print(f"target={TARGET.relative_to(REPO)}")
    print("RESULT:", "ALL CHECKS PASSED" if failed == 0 else f"{failed} CHECK(S) FAILED")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
